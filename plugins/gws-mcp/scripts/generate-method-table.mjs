#!/usr/bin/env node
// Generates src/google-api/method-table.ts from Google's Discovery documents.
//
// Every method of every service this plugin talks to is included, not only the
// ones src/tools calls today: gws_run reaches any method by name, and a table
// limited to today's call sites would turn the fallback tool into a refusal.
//
// Run: node scripts/generate-method-table.mjs   (needs network; output is committed)
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SERVICES = {
  drive: ["drive", "v3"],
  gmail: ["gmail", "v1"],
  sheets: ["sheets", "v4"],
  calendar: ["calendar", "v3"],
  docs: ["docs", "v1"],
  slides: ["slides", "v1"],
  people: ["people", "v1"],
  tasks: ["tasks", "v1"],
};

const out = {};
for (const [service, [api, version]] of Object.entries(SERVICES)) {
  const url = `https://www.googleapis.com/discovery/v1/apis/${api}/${version}/rest`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const doc = await res.json();
  const root = new URL(doc.rootUrl);
  if (root.protocol !== "https:" || !root.hostname.endsWith(".googleapis.com")) {
    throw new Error(`${service}: unexpected rootUrl ${doc.rootUrl}`);
  }
  const methods = {};
  const walk = (resources, prefix) => {
    for (const [name, resource] of Object.entries(resources ?? {})) {
      const key = prefix ? `${prefix}.${name}` : name;
      for (const [methodName, m] of Object.entries(resource.methods ?? {})) {
        const params = m.parameters ?? {};
        const entry = {
          httpMethod: m.httpMethod,
          path: m.path,
          pathParams: Object.keys(params).filter((p) => params[p].location === "path").sort(),
          repeated: Object.keys(params).filter((p) => params[p].repeated).sort(),
          requiredQuery: Object.keys(params)
            .filter((p) => params[p].required && params[p].location === "query")
            .sort(),
        };
        if (m.request) entry.hasBody = true;
        if (m.supportsMediaDownload) entry.mediaDownload = true;
        const simple = m.mediaUpload?.protocols?.simple?.path;
        const resumable = m.mediaUpload?.protocols?.resumable?.path;
        if (simple || resumable) entry.mediaUpload = { simple, resumable };
        methods[`${key}.${methodName}`] = entry;
      }
      walk(resource.resources, key);
    }
  };
  walk(doc.resources, "");
  out[service] = {
    rootUrl: doc.rootUrl,
    servicePath: doc.servicePath ?? "",
    revision: doc.revision,
    methods: Object.fromEntries(Object.entries(methods).sort(([a], [b]) => a.localeCompare(b))),
  };
  console.error(`${service}: ${Object.keys(methods).length} methods (revision ${doc.revision})`);
}

const file = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "google-api", "method-table.ts");
writeFileSync(
  file,
  `// GENERATED by scripts/generate-method-table.mjs from Google's Discovery documents.
// Do not edit by hand; re-run the script. The oracle test compares every entry
// src/tools uses against the pinned CLI's own reading of the same documents.

export interface MethodEntry {
  httpMethod: string;
  /** Discovery path template: {name} is a path segment, {+name} keeps slashes. */
  path: string;
  pathParams: string[];
  /** Query parameters the API reads as a repeated key. */
  repeated: string[];
  /** Query parameters Discovery marks required. */
  requiredQuery: string[];
  /** Whether the method takes a JSON request body. */
  hasBody?: boolean;
  mediaDownload?: boolean;
  mediaUpload?: { simple?: string; resumable?: string };
}

export interface ServiceEntry {
  rootUrl: string;
  servicePath: string;
  revision: string;
  methods: Record<string, MethodEntry>;
}

export const METHOD_TABLE: Record<string, ServiceEntry> = ${JSON.stringify(out, null, 2)};
`
);
